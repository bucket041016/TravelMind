def list_presets() -> list[dict[str, Any]]:
    """返回所有精选示例的摘要列表。"""
    return [
        {
            "id": preset["id"],
            "title": preset["title"],
            "subtitle": preset["subtitle"],
            "tags": list(preset["tags"]),
        }
        for preset in _PRESETS.values()
    ]


